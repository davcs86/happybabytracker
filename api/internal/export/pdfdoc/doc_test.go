func TestEmojiNeverReachesFpdf(t *testing.T) {
	const e = "😀"
	d := New(fixedTime, func(int) string { return e })
	d.Heading(e)
	d.Line(e, e)
	d.Paragraph(e)
	d.Table([]Col{{e, 40}}, [][]string{{e}})
	d.Chart(Chart{Title: e, XLabel: e, YLabel: e, XMax: 1, YMax: 1,
		Curves: []Curve{{Label: e, Points: []Point{{0, 0}, {1, 1}}}}, Points: []Point{{0.5, 0.5}}})
	if !d.Substituted() {
		t.Fatal("Substituted() = false after an emoji")
	}
	for _, s := range strs(slices.Concat(pageTexts(t, render(t, d))...)) {
		if strings.Contains(s, e) {
			t.Fatalf("emoji reached the output: %q", s)
		}
	}
	if New(fixedTime, footerText).Substituted() {
		t.Fatal("Substituted() = true on a clean document")
	}
}

func TestUnbrokenNoteWraps(t *testing.T) {
	d, m := New(fixedTime, footerText), New(fixedTime, footerText)
	d.Table([]Col{{"Date", 30}, {"Note", 60}}, [][]string{{"2026-11-01", strings.Repeat("x", 500)}})
	pages := pageTexts(t, render(t, d))
	right := float64(constants.ExportPageWidthMM - constants.ExportMarginMM)
	xs := 0
	for _, p := range pages {
		for i, s := range p {
			size, style := float64(constants.ExportFontSizeBody), ""
			if i < 2 {
				style = "B"
			}
			if i == len(p)-1 {
				size = constants.ExportFontSizeSmall
			}
			if w := m.testWidth(s.S, style, size); s.X+w > right+1e-6 || s.X < constants.ExportMarginMM-1e-6 {
				t.Errorf("%q at x %.2f width %.2f leaves the margins", s.S, s.X, w)
			}
			if s.Y > constants.ExportPageHeightUsableMM || s.Y < constants.ExportMarginMM {
				t.Errorf("%q at y %.2f is outside the usable height", s.S, s.Y)
			}
			if strings.Trim(s.S, "x") == "" {
				xs += len(s.S)
				if w := m.testWidth(s.S, style, size); w > 60 {
					t.Errorf("a wrapped line is %.2f mm wide in a 60 mm column", w)
				}
			}
		}
	}
	if xs != 500 {
		t.Fatalf("wrapped lines hold %d x, want 500", xs)
	}
}

func TestTableRepeatsHeader(t *testing.T) {
	d := New(fixedTime, footerText)
	cols := []Col{{"Date", 30}, {"Amount", 25}, {"Note", 60}}
	rows := make([][]string, 200)
	for i := range rows {
		rows[i] = []string{fmt.Sprintf("row %03d", i), "120 ml", "note"}
	}
	d.Table(cols, rows)
	pages := pageTexts(t, render(t, d))
	if len(pages) < 3 {
		t.Fatalf("pages = %d, want several", len(pages))
	}
	seen := 0
	for n, p := range pages {
		if got := strs(p[:3]); fmt.Sprint(got) != "[Date Amount Note]" {
			t.Fatalf("page %d starts with %q, want the header", n+1, got)
		}
		for _, s := range p {
			if strings.HasPrefix(s.S, "row ") {
				seen++
			}
		}
	}
	if seen != 200 {
		t.Fatalf("rows printed = %d, want 200", seen)
	}
}

func TestFooterOnEveryPage(t *testing.T) {
	d := New(fixedTime, func(page int) string { return fmt.Sprintf("left %d", page) })
	rows := make([][]string, 150)
	for i := range rows {
		rows[i] = []string{"cell"}
	}
	d.Table([]Col{{"Title", 40}}, rows)
	pages := pageTexts(t, render(t, d))
	if len(pages) < 2 {
		t.Fatalf("pages = %d, want several", len(pages))
	}
	for n, p := range pages {
		last := p[len(p)-1]
		want := fmt.Sprintf("left %d · Page %d of %d", n+1, n+1, len(pages))
		if last.S != want {
			t.Fatalf("page %d footer = %q, want %q", n+1, last.S, want)
		}
		if last.Y > constants.ExportPageHeightUsableMM {
			t.Fatalf("page %d footer at y %.2f, below the usable height", n+1, last.Y)
		}
	}
}

func TestNoForbiddenObjects(t *testing.T) {
	pdf := render(t, sampleDoc(fixedTime))
	// fpdf v0.12.0 always writes an empty /EmbeddedFiles name tree in the catalog; only that exact empty form is masked.
	emptyTree := regexp.MustCompile(`/EmbeddedFiles << /Names \[\s*\] >>`)
	if len(emptyTree.FindAllIndex(pdf, -1)) > 1 {
		t.Error("more than one /EmbeddedFiles name tree")
	}
	masked := emptyTree.ReplaceAll(pdf, nil)
	for _, s := range []string{"/JavaScript", "/JS", "/URI", "/Launch", "/EmbeddedFile", "/Type /XObject", "/Subtype /Image", "/Encrypt"} {
		if bytes.Contains(masked, []byte(s)) {
			t.Errorf("output contains %q", s)
		}
	}
	all := regexp.MustCompile(`/XObject\b`).FindAllIndex(pdf, -1)
	empty := regexp.MustCompile(`/XObject <<\s*>>`).FindAllIndex(pdf, -1)
	if len(all) == 0 || len(all) != len(empty) {
		t.Errorf("/XObject dictionaries: %d, empty: %d; want every one empty", len(all), len(empty))
	}
	var names []string
	for _, m := range regexp.MustCompile(`/BaseFont /(\S+)`).FindAllSubmatch(pdf, -1) {
		names = append(names, string(m[1]))
	}
	slices.Sort(names)
	if got := fmt.Sprint(slices.Compact(names)); got != "[utf8notosans utf8notosansB]" {
		t.Errorf("/BaseFont names = %s, want only the two embedded Noto Sans subsets", got)
	}
	if !bytes.Contains(pdf, []byte("/FontFile2 ")) {
		t.Error("no embedded font file")
	}
}

