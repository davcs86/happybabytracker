var fixedTime = time.Date(2026, 11, 24, 13, 5, 0, 0, time.UTC)

func render(t *testing.T, d *Doc) []byte {
	t.Helper()
	var b bytes.Buffer
	n, err := d.WriteTo(&b)
	if err != nil {
		t.Fatalf("WriteTo: %v", err)
	}
	if n != int64(b.Len()) {
		t.Fatalf("WriteTo returned %d, wrote %d", n, b.Len())
	}
	return b.Bytes()
}

// testWidth is the width in mm of s in style ("" or "B") at size points.
func (d *Doc) testWidth(s, style string, size float64) float64 {
	d.f.SetFont(family, style, size)
	return d.f.GetStringWidth(s)
}

func footerText(int) string { return "Generated by happybabytracker" }

func sampleDoc(created time.Time) *Doc {
	d := New(created, footerText)
	d.Heading("Profile")
	d.Line("Name", "Zoë Müller-Señor")
	d.Line("Other names", "Ольга Ελένη Łucja Ștefan")
	d.Paragraph("Source: an attribution in small print, long enough to wrap across the full width of the page at least once.")
	d.Heading("Bottles")
	d.Table([]Col{{"Date", 30}, {"Amount", 25}, {"Note", 60}}, [][]string{
		{"2026-11-01", "120 ml", "Ελένη fed"},
		{"2026-11-02", "90 ml", "Ольга fed (a\\b)"},
	})
	d.Chart(Chart{
		Title: "Weight for age", XLabel: "Age (months)", YLabel: "Weight (kg)",
		XMin: 0, XMax: 24, YMin: 2, YMax: 16,
		Curves: []Curve{
			{Label: "P3", Points: []Point{{0, 2.5}, {12, 7.5}, {24, 9.5}}},
			{Label: "P97", Points: []Point{{0, 4.3}, {12, 11.5}, {24, 14.5}}},
		},
		Points: []Point{{1, 4}, {6, 7.8}, {12, 9.6}},
	})
	return d
}

func TestDeterministic(t *testing.T) {
	a, b := render(t, sampleDoc(fixedTime)), render(t, sampleDoc(fixedTime))
	if !bytes.Equal(a, b) {
		t.Fatal("same clock and text gave different bytes")
	}
	c := render(t, sampleDoc(fixedTime.Add(49*time.Hour+7*time.Minute+3*time.Second)))
	if bytes.Equal(a, c) {
		t.Fatal("a different clock gave identical bytes")
	}
	if !bytes.Contains(a, []byte("/CreationDate (D:20261124130500)")) {
		t.Fatal("creation date is not the given UTC instant")
	}
	dates := regexp.MustCompile(`/(CreationDate|ModDate) \(D:\d{14}\)`)
	mask := func(p []byte) []byte { return dates.ReplaceAll(p, []byte("/$1 (D:00000000000000)")) }
	if !bytes.Equal(mask(a), mask(c)) {
		t.Fatal("a different clock changed bytes other than the dates")
	}
	if bytes.Contains(a, []byte("/Author")) || !bytes.Contains(a, []byte("/Producer ("+constants.ExportProducer+")")) ||
		!bytes.Contains(a, []byte("/Title ("+constants.ExportTitle+")")) {
		t.Fatal("metadata is not the fixed producer and title without an author")
	}
}

func TestGolden(t *testing.T) {
	got := render(t, sampleDoc(fixedTime))
	path := filepath.Join("testdata", "doc.golden.pdf")
	if os.Getenv("UPDATE_GOLDEN") == "1" {
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (run with UPDATE_GOLDEN=1)", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("document differs from testdata/doc.golden.pdf (run with UPDATE_GOLDEN=1 and review the diff)")
	}
	texts := strings.Join(strs(slices.Concat(pageTexts(t, got)...)), "|")
	for _, s := range []string{"Zoë Müller-Señor", "Ольга Ελένη Łucja Ștefan", "Ελένη fed", "Ольга fed (a\\b)", "P97"} {
		if !strings.Contains(texts, s) {
			t.Errorf("golden text lacks %q", s)
		}
	}
}

