func TestChartInsideMargins(t *testing.T) {
	d := New(fixedTime, footerText)
	d.Chart(Chart{Title: "t", XLabel: "x", YLabel: "y", XMin: 0, XMax: 10, YMin: 0, YMax: 10,
		Curves: []Curve{{Label: "a long curve label", Points: []Point{{-5, 1}, {0, 0}, {10, 10}, {20, 30}}}},
		Points: []Point{{-100, 5}, {5, 1000}, {0, 0}, {10, 10}, {11, 3}}})
	pdf := render(t, d)
	ops := regexp.MustCompile(`([-\d.]+) ([-\d.]+) (m|l)\b|([-\d.]+) ([-\d.]+) ([-\d.]+) ([-\d.]+) re\b`)
	pages := regexp.MustCompile(`(?s)<</Length \d+>>\nstream\n(.*?)\nendstream`).FindSubmatch(pdf)
	content := pages[1]
	left, right := float64(constants.ExportMarginMM)*ptPerMM, float64(constants.ExportPageWidthMM-constants.ExportMarginMM)*ptPerMM
	top := (constants.ExportPageHeightMM - float64(constants.ExportMarginMM)) * ptPerMM
	bottom := (constants.ExportPageHeightMM - constants.ExportPageHeightUsableMM) * ptPerMM
	var n int
	for _, m := range ops.FindAllSubmatch(content, -1) {
		var x, y float64
		if m[3] != nil {
			fmt.Sscan(string(m[1])+" "+string(m[2]), &x, &y)
		} else {
			var w, h float64
			fmt.Sscan(string(m[4])+" "+string(m[5])+" "+string(m[6])+" "+string(m[7]), &x, &y, &w, &h)
			if x+w > right+0.01 || y+h < bottom-0.01 {
				t.Errorf("rect %s leaves the margins", m[0])
			}
		}
		n++
		if x < left-0.01 || x > right+0.01 || y > top+0.01 || y < bottom-0.01 {
			t.Errorf("path point %s leaves the margins", m[0])
		}
	}
	if n == 0 {
		t.Fatal("no path operators found")
	}
	for _, op := range regexp.MustCompile(`([\d.]+) ([\d.]+) ([\d.]+) (RG|rg)\b`).FindAllSubmatch(content, -1) {
		if string(op[1]) != string(op[2]) || string(op[2]) != string(op[3]) {
			t.Errorf("colour %s is not grey or black", op[0])
		}
	}
}

